import { writeFileSync } from "node:fs";
import { Document, isCollection, visit } from "yaml";
import { layout_description } from "./layouts.js";

// byte offset of the node commands in the unit of an actuator (doc/spec-modbus.md)
const COMMAND_START = 400;

const HEADER = "# Emulator description generated by the controller at startup; edits are overwritten.\n";

/**
 * Describes the data blocks of a controller and the Modbus server that
 * publishes them upward, for modbus-emulator (doc/design.md 4.4). Reads the
 * block names from the object graph and changes nothing.
 *
 * The blocks are placed by one unit entry per unit id; the unit options keep
 * their defaults (big-endian, unmapped reads as 0 and writes ignored, all
 * points writable). The description names no scope: the emulator is
 * constructed with LAYOUT_SCOPE.
 *
 * @param {Object} controller - The controller returned by prepare_controller.
 * @return {Object} The description: layouts, item_tables, blocks, units and servers.
 */
export function build_description(controller) {
	const unit_ids = controller.modbus_server.unit_id;
	const blocks = [];
	// unit id -> placements of the unit (block name -> { start })
	const placements = new Map();
	const add = (name, layout, unit_id, start = 0) => {
		blocks.push({ name, layout });
		if (!placements.has(unit_id)) placements.set(unit_id, {});
		placements.get(unit_id)[name] = start === 0 ? {} : { start };
	};

	add(controller.record_name, "RECORD", unit_ids.action_records);
	for (const line of controller.lines) {
		add(line.name, "LINE", unit_ids[line.name]);
		for (const section of line.sections) {
			add(section.name, "SECTION", unit_ids[section.name]);
			for (const node of [...section.begin_nodes, ...section.end_nodes]) {
				add(node.name, "NODE", unit_ids[node.name]);
				add(node.command_name, "COMMAND", unit_ids[node.name], COMMAND_START);
			}
		}
	}

	return {
		...layout_description,
		blocks,
		units: [...placements].map(([unit_id, placed]) => ({ unit_id, blocks: placed })),
		servers: [{ protocol: "tcp", host: "0.0.0.0", port: controller.modbus_server.port }],
	};
}

/**
 * Writes a description as a YAML file, replacing the file. A mapping without
 * a collection value is written on one line, like the items of layouts.yaml,
 * so that the items and the blocks read as tables.
 */
export function write_description(file, description) {
	const document = new Document(description, { version: "1.2" });
	visit(document, {
		Map(_, node) {
			if (!node.items.some((pair) => isCollection(pair.value))) node.flow = true;
		},
	});
	writeFileSync(file, HEADER + document.toString({ indentSeq: false, lineWidth: 0 }));
}
